export function loadSaveData(): PlayerSaveData {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return getDefaultSaveData();
    const data = JSON.parse(raw);
    const defaults = getDefaultSaveData();

    // Merge safely to preserve new fields across versions
    return {
      ...defaults,
      ...data,
      unlockedBikes: Array.isArray(data.unlockedBikes) ? data.unlockedBikes : defaults.unlockedBikes,
      bikeUpgrades: { ...defaults.bikeUpgrades, ...(data.bikeUpgrades || {}) },
      unlockedMaps: Array.isArray(data.unlockedMaps) ? data.unlockedMaps : defaults.unlockedMaps,
      missions: Array.isArray(data.missions) ? data.missions : defaults.missions,
      settings: { ...defaults.settings, ...(data.settings || {}) },
    };
  } catch (err) {
    console.error('Failed to load save data, resetting to default:', err);
    return getDefaultSaveData();
  }
}

export function savePlayerData(data: PlayerSaveData): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (err) {
    console.error('Failed to save player data:', err);
  }
}

export function calculateUpgradedBikeStats(bike: MotorcycleStats, upgrades: BikeUpgrades) {
  const engineBoost = (upgrades.engine || 0) * 0.04; // +4% max speed & acceleration per level
  const brakeBoost = (upgrades.brakes || 0) * 0.05; // +5% braking per level
  const handlingBoost = (upgrades.handling || 0) * 0.05; // +5% handling per level
  const nitroBoost = (upgrades.nitro || 0) * 0.5; // +0.5s nitro capacity per level

  return {
    maxSpeed: Math.round(bike.baseMaxSpeed * (1 + engineBoost)),
    acceleration: +(bike.baseAcceleration * (1 + engineBoost)).toFixed(2),
    handling: +(bike.baseHandling * (1 + handlingBoost)).toFixed(2),
    braking: +(bike.baseBraking * (1 + brakeBoost)).toFixed(2),
    nitroDuration: +(bike.baseNitro + nitroBoost).toFixed(1),
  };
}

export function getUpgradeCost(level: number): number {
  const costs = [1000, 2500, 5000, 9000, 15000];
  return costs[level] || 25000;
}
